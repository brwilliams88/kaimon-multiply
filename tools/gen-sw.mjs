// Regenerates sw.js with the current file list and version.
// Run after any change: node tools/gen-sw.mjs
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

const root = new URL('..', import.meta.url).pathname;
const include = ['index.html', 'manifest.webmanifest', 'css', 'js', 'fonts', 'icons', 'assets'];
const files = [];
const walk = (p) => {
  let st;
  try { st = statSync(p); } catch { return; }
  if (st.isDirectory()) readdirSync(p).forEach((f) => walk(join(p, f)));
  else if (!/\.(md|txt)$/.test(p) && !p.endsWith('.DS_Store')) files.push(relative(root, p));
};
// Pictures for emails (assets/email) are only loaded by email apps, never by the
// game, so they stay out of the offline cache.
const forApp = (f) => !f.startsWith('assets/email/');
include.forEach((f) => walk(join(root, f)));
files.splice(0, files.length, ...files.filter(forApp));
files.sort();

const version = /VERSION = '([^']+)'/.exec(readFileSync(join(root, 'js/data/changelog.js'), 'utf8'))[1];
const h = createHash('sha256');
files.forEach((f) => h.update(f).update(readFileSync(join(root, f))));
const build = h.digest('hex').slice(0, 10);

// App files are cached per version. Art (assets/, about 13 MB) lives in its own
// cache that survives updates: each file is keyed by its content hash, so an
// update only downloads art that actually changed.
const core = files.filter((f) => !f.startsWith('assets/'));
const art = Object.fromEntries(files.filter((f) => f.startsWith('assets/'))
  .map((f) => [f, createHash('sha256').update(readFileSync(join(root, f))).digest('hex').slice(0, 8)]));

const sw = `// Generated by tools/gen-sw.mjs. Do not edit by hand.
const CACHE = 'kaimon-${version}-${build}';
const ART_CACHE = 'kaimon-art';
const ASSETS = ${JSON.stringify(['./', ...core], null, 2)};
const ART = ${JSON.stringify(art)};
const artKey = (path) => new URL(path + '?v=' + ART[path], self.registration.scope).href;

self.addEventListener('install', (e) => {
  // cache: 'reload' skips the browser's HTTP cache, so a new version never stores old files.
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS.map((u) => new Request(u, { cache: 'reload' })))));
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k !== CACHE && k !== ART_CACHE) await caches.delete(k);
    // Drop art that is no longer used, or that changed.
    const art = await caches.open(ART_CACHE);
    const keep = new Set(Object.keys(ART).map(artKey));
    for (const req of await art.keys()) if (!keep.has(req.url)) await art.delete(req);
    await self.clients.claim();
  })());
});

// Fill the art cache in the background so the whole game works offline.
async function warmArt() {
  const art = await caches.open(ART_CACHE);
  for (const path of Object.keys(ART)) {
    const key = artKey(path);
    if (await art.match(key)) continue;
    try { const r = await fetch(path, { cache: 'reload' }); if (r.ok) await art.put(key, r); } catch { return; }
  }
}

self.addEventListener('message', (e) => {
  if (e.data === 'skipWaiting') self.skipWaiting();
  if (e.data === 'warmArt') e.waitUntil(warmArt());
});

async function artResponse(path, request) {
  const art = await caches.open(ART_CACHE);
  const key = artKey(path);
  const hit = await art.match(key);
  if (hit) return hit;
  const r = await fetch(request);
  if (r.ok) art.put(key, r.clone());
  return r;
}

self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return;
  const scope = new URL(self.registration.scope).pathname;
  const path = url.pathname.startsWith(scope) ? decodeURIComponent(url.pathname.slice(scope.length)) : '';
  if (ART[path]) { e.respondWith(artResponse(path, e.request)); return; }
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).catch(() => {
      if (e.request.mode === 'navigate') return caches.match('./');
    }))
  );
});
`;
writeFileSync(join(root, 'sw.js'), sw);
// version.json is never cached, so the app can always ask what the newest version is.
writeFileSync(join(root, 'version.json'), JSON.stringify({ version, build }) + '\n');
console.log(`sw.js: ${core.length} app files, ${Object.keys(art).length} art files, cache ${version}-${build}`);
