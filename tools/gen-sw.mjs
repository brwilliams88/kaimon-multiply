// Regenerates sw.js with the current file list and version.
// Run after any change: node tools/gen-sw.mjs
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

const root = new URL('..', import.meta.url).pathname;
const include = ['index.html', 'manifest.webmanifest', 'css', 'js', 'fonts', 'icons', 'assets'];
const files = [];
const walk = (p) => {
  let st;
  try { st = statSync(p); } catch { return; }
  if (st.isDirectory()) readdirSync(p).forEach((f) => walk(join(p, f)));
  else if (!/\.(md|txt)$/.test(p) && !p.endsWith('.DS_Store')) files.push(relative(root, p));
};
include.forEach((f) => walk(join(root, f)));
files.sort();

const version = /VERSION = '([^']+)'/.exec(readFileSync(join(root, 'js/data/changelog.js'), 'utf8'))[1];
const h = createHash('sha256');
files.forEach((f) => h.update(f).update(readFileSync(join(root, f))));
const build = h.digest('hex').slice(0, 10);

const sw = `// Generated by tools/gen-sw.mjs. Do not edit by hand.
const CACHE = 'kaimon-${version}-${build}';
const ASSETS = ${JSON.stringify(['./', ...files], null, 2)};

self.addEventListener('install', (e) => {
  // cache: 'reload' skips the browser's HTTP cache, so a new version never stores old files.
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS.map((u) => new Request(u, { cache: 'reload' })))));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});

self.addEventListener('message', (e) => { if (e.data === 'skipWaiting') self.skipWaiting(); });

self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).catch(() => {
      if (e.request.mode === 'navigate') return caches.match('./');
    }))
  );
});
`;
writeFileSync(join(root, 'sw.js'), sw);
// version.json is never cached, so the app can always ask what the newest version is.
writeFileSync(join(root, 'version.json'), JSON.stringify({ version, build }) + '\n');
console.log(`sw.js: ${files.length} files, cache ${version}-${build}`);
